def test_retrieval_failure_returns_explicit_error_without_output(monkeypatch):
    import pipeline

    pipeline._KNOWLEDGE_BASE = None

    def fail_ingestion(_data_dir):
        raise IngestionError(Path("data"), "unreadable file")

    monkeypatch.setattr(pipeline, "ingest_directory", fail_ingestion)
    result = run_pipeline("pothole", llm=MockLLMClient([]))

    assert result["status"] == "error"
    assert "unreadable file" in result["error"]
    assert "action_items" not in result


def test_output_caps_items_and_summary_length(tmp_path):
    source = tmp_path / "feedback.txt"
    source.write_text("Pothole on Main Street.", encoding="utf-8")
    ingest_documents([source])
    from ingest import ingest_files

    chunk = ingest_files([source])[0]
    action = {
        "category": "roads",
        "location": "Main Street",
        "priority": "high",
        "suggested_department": "Roads",
        "summary": "x" * 800,
        "citations": [{"doc_id": chunk.doc_id, "chunk_id": chunk.chunk_id, "excerpt": "Pothole"}],
    }
    response = json.dumps(
        {"status": "ok", "action_items": [action.copy() for _ in range(7)]}
    )
    result = run_pipeline("pothole", llm=MockLLMClient([response]))

    assert result["status"] == "ok"
    assert len(result["action_items"]) == 5
    assert all(len(item["summary"]) == 500 for item in result["action_items"])
